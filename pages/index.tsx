import { useState } from "react";
import { Inter } from "@next/font/google";
import Head from "next/head";
import Image from "next/image";
import Search from "../components/search/Search";
import Weather from "../components/weather/Weather";
import Spinner from "../components/spinner/Spinner";
import Notification from "../components/notification/Notification";
import useTranslation from "../hooks/useTranslation";
import useWeather from "../hooks/useWeather";
import type { NotificationProps } from "../components/notification/Notification.types";
import type { SearchProps } from "../components/search/Search.types";

const inter = Inter({ subsets: ["latin"] });

export default function Home() {
  const [snackbarMessage, setSnackbarMessage] = useState<string | null>("");
  const [city, setCity] = useState("");
  const [isOpen, setIsOpen] = useState(false);

  const { t, toggleLocale } = useTranslation();

  const showError = (message: string) => {
    setSnackbarMessage(message);
    setIsOpen(true);
  };

  const { weather, isLoading, getWeather } = useWeather({
    onError: showError,
  });

  const handleLanguageChange = () => {
    toggleLocale();
    setSnackbarMessage(null);
    setIsOpen(true);
  };

  const handleToClose: NotificationProps["handleToClose"] = (
    _event,
    reason,
  ) => {
    if ("clickaway" == reason) {
      return;
    }
    setIsOpen(false);
  };

  const fetchWeather: SearchProps["fetchWeather"] = (e) => {
    e.preventDefault();
    getWeather(city);
    setCity("");
  };

  return (
    <div>
      <Head>
        <title>WeatherNext</title>
        <meta name='description' content='Generated by create next app' />
        <meta name='viewport' content='width=device-width, initial-scale=1' />
        <link rel='icon' href='/weatherFavicon.ico' />
      </Head>

      {/* Overlay */}
      <div className='absolute top-0 left-0 right-0 bottom-0 bg-black/60 z-[1]' />

      {/* Background Image */}
      <Image
        alt='background'
        src='https://images.pexels.com/photos/296559/pexels-photo-296559.jpeg'
        layout='fill'
        className='object-cover'
      />

      {/* Search */}
      <Search
        {...{ fetchWeather }}
        {...{ setCity }}
        {...{ handleLanguageChange }}
      />
      {/* Search end */}

      <Notification
        isOpen={isOpen}
        message={snackbarMessage || t("langSB")}
        {...{ handleToClose }}
      />

      {isLoading ? (
        <Spinner />
      ) : (
        /* Weather */
        weather && <Weather data={weather} />
        /* Weather end */
      )}
    </div>
  );
}
