import { useEffect, useState } from "react";
import { Inter } from "@next/font/google";
import axios from "axios";
import Head from "next/head";
import Image from "next/image";
import Search from "../components/Search";
import Weather from "../components/Weather";
import Spinner from "../components/Spinner";
import useTranslation from "../hooks/useTranslation";

const inter = Inter({ subsets: ["latin"] });

export default function Home() {
  const [snackbarMessage, setSnackbarMessage] = useState("");
  const [weather, setWeather] = useState({});
  const [city, setCity] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [isOpen, setIsOpen] = useState(false);
  const [lastCity, setLastCity] = useState("");

  const { t, locale, toggleLocale } = useTranslation();

  const handleLanguageChange = () => {
    toggleLocale();
    setSnackbarMessage(null);
    setIsOpen(true);
  };

  const handleToClose = (event, reason) => {
    if ("clickaway" == reason) {
      return;
    }
    setIsOpen(false);
  };

  const getWeather = (query) => {
    const url = `https://api.openweathermap.org/data/2.5/weather?q=${query}&units=metric&lang=${t("apiLang")}&appid=${process.env.NEXT_PUBLIC_WEATHER_KEY}`;
    setIsLoading(true);
    axios
      .get(url)
      .then((response) => {
        setWeather(response.data);
        setLastCity(query);
      })
      .catch((error) => {
        const message =
          t("errorMessage") ||
          error.response?.data?.message ||
          "Something went wrong. Please try again.";
        setSnackbarMessage(message);
        setIsOpen(true);
      })
      .finally(() => {
        setIsLoading(false);
      });
  };

  const fetchWeather = (e) => {
    e.preventDefault();
    getWeather(city);
    setCity("");
  };

  // Refetch the displayed city so the API description matches the new locale
  // Maybe too much for a translation, but for an app this small, it works.
  useEffect(() => {
    if (lastCity) {
      getWeather(lastCity);
    }
  }, [locale]);
  return (
    <div>
      <Head>
        <title>WeatherNext</title>
        <meta name='description' content='Generated by create next app' />
        <meta name='viewport' content='width=device-width, initial-scale=1' />
        <link rel='icon' href='/weatherFavicon.ico' />
      </Head>

      {/* Overlay */}
      <div className='absolute top-0 left-0 right-0 bottom-0 bg-black/60 z-[1]' />

      {/* Background Image */}
      <Image
        alt='background'
        src='https://images.pexels.com/photos/296559/pexels-photo-296559.jpeg'
        layout='fill'
        className='object-cover'
      />

      {/* Search */}
      <Search
        isOpen={isOpen}
        snackbarMessage={snackbarMessage}
        {...{ fetchWeather }}
        {...{ setCity }}
        {...{ handleLanguageChange }}
        {...{ handleToClose }}
      />
      {/* Search end */}

      {isLoading ? (
        <Spinner />
      ) : (
        /* Weather */
        weather.main && <Weather data={weather} />
        /* Weather end */
      )}
    </div>
  );
}
